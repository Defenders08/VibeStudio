//! Синтез: кик-сэмпл (генерируется детерминированно при старте) и тон.

/// Частота MIDI-ключа (A4 = 440 Гц).
pub fn key_freq(key: u16) -> f32 {
    440.0 * 2.0f32.powf((key as f32 - 69.0) / 12.0)
}

/// Синтезированный кик ~0.35 с: синус со свипом 165→45 Гц, экспоненциальный
/// спад, короткий «клик» в атаке. Детерминированный (одинаков в live и рендере).
pub fn kick_sample(sr: f32) -> Vec<f32> {
    let dur = 0.35;
    let n = (sr * dur) as usize;
    let mut out = Vec::with_capacity(n);
    for i in 0..n {
        let t = i as f32 / sr;
        let env = (-t * 11.0).exp();
        // свип частоты: логарифмический от 165 к 45 Гц за 0.12 с, дальше 45
        let f = if t < 0.12 {
            165.0 * (45.0 / 165.0f32).powf(t / 0.12)
        } else {
            45.0
        };
        let mut s = (2.0 * std::f32::consts::PI * f * t).sin() * env;
        // клик атаки (3 мс широкополосный), приглушён чтобы пик оставался < 1
        if t < 0.003 {
            s += (0.003 - t) / 0.003 * 0.4 * (t * sr * 997.0).sin();
        }
        out.push((s * 0.85).clamp(-0.98, 0.98));
    }
    out
}
